function hitungJungkit_Jungkit12BouvenUnik() {
    let inputTinggi = document.getElementById('inputTinggi_Jungkit12BouvenUnik');
    let inputLebar = document.getElementById('inputLebar_Jungkit12BouvenUnik');

    if (!inputTinggi || !inputLebar) {
        return;
    }

    let tinggi = parseInt(inputTinggi.value) || 0;
    let lebar = parseInt(inputLebar.value) || 0;
    
    let angkaTinggi = document.getElementById('angkaTinggi_Jungkit12BouvenUnik');
    let angkaLebar = document.getElementById('angkaLebar_Jungkit12BouvenUnik');
    
    if (angkaTinggi) angkaTinggi.textContent = (tinggi > 0 ? tinggi : 0) + ' cm';
    if (angkaLebar) angkaLebar.textContent = (lebar > 0 ? lebar : 0) + ' cm';
    
    // VALIDASI BOUVEN
    let warningTinggi = document.getElementById('warningTinggi_Jungkit12BouvenUnik');
    let warningLebar = document.getElementById('warningLebar_Jungkit12BouvenUnik');
    let btnSubmit = document.getElementById('submit_Jungkit12BouvenUnik');
    let isError = false;

    if (tinggi > 70) {
        warningTinggi.style.display = 'block';
        isError = true;
    } else {
        warningTinggi.style.display = 'none';
    }

    if (lebar > 1440) {
        warningLebar.style.display = 'block';
        isError = true;
    } else {
        warningLebar.style.display = 'none';
    }

    btnSubmit.disabled = isError;
    btnSubmit.style.opacity = isError ? '0.5' : '1';
    btnSubmit.style.cursor = isError ? 'not-allowed' : 'pointer';

    if (tinggi > 0 && lebar > 0 && !isError) {
        let container = document.getElementById('jendelaContainer_Jungkit12BouvenUnik');
        if (!container) return;

        let maxSize = 400;
        let scale = Math.min(1, maxSize / Math.max(tinggi, lebar));
        let displayWidth = lebar * scale;
        let displayHeight = tinggi * scale;
        
        container.style.width = (displayWidth + 40) + 'px';
        container.style.height = (displayHeight + 60) + 'px';
        container.style.minWidth = '200px';
        container.style.minHeight = '150px';
        
        let kusen = document.getElementById('kusen_Jungkit12BouvenUnik');
        if (!kusen) return;
        kusen.style.width = displayWidth + 'px';
        kusen.style.height = displayHeight + 'px';
        let borderThick = Math.max(4, Math.min(12, Math.floor(displayWidth * 0.04)));
        kusen.style.borderWidth = borderThick + 'px';
        
        let gap = 4; 
        let kacaWidth = displayWidth - (borderThick * 2) - (gap * 2);
        let kacaHeight = displayHeight - (borderThick * 2) - (gap * 2);
        
        // 12 DAUN SAMA RATA
        let lebarSatuDaun = kacaWidth / 12;

        // Ambil semua wrapper
        let wrappers = [];
        for (let i = 1; i <= 12; i++) {
            wrappers.push(document.getElementById('daunWrapper' + i + '_Jungkit12BouvenUnik'));
        }
        if (wrappers.some(w => !w)) return;
        
        // Posisi
        let posX = gap;
        for (let i = 0; i < 12; i++) {
            let w = wrappers[i];
            w.style.width = lebarSatuDaun + 'px';
            w.style.height = kacaHeight + 'px';
            w.style.top = gap + 'px';
            w.style.left = posX + 'px';
            w.style.transformOrigin = 'top center';
            document.getElementById('daunKaca' + (i + 1) + '_Jungkit12BouvenUnik').style.width = lebarSatuDaun + 'px';
            document.getElementById('daunKaca' + (i + 1) + '_Jungkit12BouvenUnik').style.height = kacaHeight + 'px';

            // Coupling (hanya sampai 11)
            if (i < 11) {
                let c = document.getElementById('coupling' + (i + 1) + '_Jungkit12BouvenUnik');
                if (c) {
                    c.style.left = (posX + lebarSatuDaun) + 'px';
                    c.style.top = '0px';
                    c.style.height = displayHeight;
                }
            }
            posX += lebarSatuDaun;
        }
    }
}

