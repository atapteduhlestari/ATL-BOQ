let isJungkitOpen_Jungkit2V2H2 = false;

function toggleJungkit_Jungkit2V2H2() {
    isJungkitOpen_Jungkit2V2H2 = !isJungkitOpen_Jungkit2V2H2;
    let wrapperKiri = document.getElementById('daunWrapperKiri_Jungkit2V2H2');
    let wrapperKanan = document.getElementById('daunWrapperKanan_Jungkit2V2H2');
    let btn = document.getElementById('toggleJungkitBtn_Jungkit2V2H2');
    let status = document.getElementById('statusJungkit_Jungkit2V2H2');

    if (!wrapperKiri || !wrapperKanan || !btn || !status) return;

    if (isJungkitOpen_Jungkit2V2H2) {
        wrapperKiri.style.transform = 'rotateX(-70deg)';
        wrapperKanan.style.transform = 'rotateX(-70deg)';
        btn.innerHTML = '🔒 Tutup Jendela';
        status.textContent = 'Terbuka';
        status.style.color = '#28a745';
    } else {
        wrapperKiri.style.transform = 'rotateX(0deg)';
        wrapperKanan.style.transform = 'rotateX(0deg)';
        btn.innerHTML = '🔓 Buka Jendela';
        status.textContent = 'Tertutup';
        status.style.color = '#555';
    }
}

function hitungJungkit_Jungkit2V2H2() {
    let inputTinggi = document.getElementById('inputTinggi_Jungkit2V2H2');
    let inputLebar = document.getElementById('inputLebar_Jungkit2V2H2');

    if (!inputTinggi || !inputLebar) {
        return;
    }

    let tinggi = parseInt(inputTinggi.value) || 0;
    let lebar = parseInt(inputLebar.value) || 0;
    
